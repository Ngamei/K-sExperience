/**
 * Automated data completeness & validation report → docs/DATA_REPORT.md
 *   npm run data:report
 * Counts what is actually in the repository; never estimates.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { DishCatalogueSchema, MappingFileSchema, RestaurantFileSchema } from "../src/lib/data/schema";
import { normalizeVi } from "../src/lib/search/normalize";

const root = path.resolve(__dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), "utf8"));
const cat = DishCatalogueSchema.parse(read("data/vietnamese-dishes.json"));
const { provinces } = read("data/provinces.json") as { provinces: { id: string; nameVi: string; regionId: string }[] };
const { regions } = read("data/regions.json") as { regions: { id: string; nameVi: string }[] };
const restaurants = RestaurantFileSchema.parse(read("data/hcmc-restaurants.json")).restaurants;
const links = MappingFileSchema.parse(read("data/dish-restaurant-mapping.json")).links;
const photosMeta = read("data/source/dish-photos.json").metadata;
const d = cat.dishes;
const pct = (n: number, t = d.length) => `${n} / ${t} (${t ? Math.round((n / t) * 100) : 0}%)`;

// Possible duplicates: identical normalised names, or one name contained in another within the same province.
const dupes: string[] = [];
for (let i = 0; i < d.length; i++)
  for (let j = i + 1; j < d.length; j++) {
    const a = normalizeVi(d[i].nameVi), b = normalizeVi(d[j].nameVi);
    const sameProv = d[i].origins.some((o) => o.provinceId && d[j].origins.some((p) => p.provinceId === o.provinceId));
    if (a === b || (sameProv && (a.includes(b) || b.includes(a)))) dupes.push(`${d[i].nameVi} ↔ ${d[j].nameVi}`);
  }

const venueCount = new Map<string, number>();
links.forEach((l) => venueCount.set(l.dishId, (venueCount.get(l.dishId) ?? 0) + 1));
const covered = new Set(d.flatMap((x) => x.origins.map((o) => o.provinceId)).filter(Boolean));
const byCat = (c: string) => d.filter((x) => x.category === c).length;
const exactPins = restaurants.filter((r) => r.coordinatePrecision === "exact").length;

const md = `# Data completeness & validation report

_Generated by \`npm run data:report\` on ${new Date().toISOString().slice(0, 10)} from the files in \`data/\`. Counts are actual repository contents, not targets._

## Catalogue (\`data/vietnamese-dishes.json\`)

| Metric | Actual | Sprint-2 target |
| --- | --- | --- |
| Dataset | **${cat.metadata.dataset}** — ${cat.metadata.label} | master catalogue |
| Dishes | ${d.length} | 500+ |
| Savory / Sweet / Snack | ${byCat("savory")} / ${byCat("sweet")} / ${byCat("snack")} | 300+ / 100+ / 100+ |
| Culinary regions with dishes | ${new Set(d.flatMap((x) => x.regionIds)).size} / 6 | 6 |
| Historical provinces with ≥1 dish | ${covered.size} / 63 | 63 |
| Dishes with source references | ${pct(d.filter((x) => x.sources.length).length)} | 100% |
| Dishes verified | ${pct(d.filter((x) => x.verification.status === "verified").length)} | — |
| Dishes with EN + VI description | ${pct(d.filter((x) => x.description.en && x.description.vi).length)} | 100% |
| Dishes with ingredients | ${pct(d.filter((x) => x.ingredients.length).length)} | 100% |
| Dishes with taste profile | ${pct(d.filter((x) => x.taste.length).length)} | 100% |
| Dishes with meal suitability | ${pct(d.filter((x) => x.mealTimes.length).length)} | 100% |
| Dishes with a licensed photo | ${pct(d.filter((x) => x.photos.length).length)} | one accurate image per dish |
| Regional-variant families | ${new Set(d.map((x) => x.family).filter(Boolean)).size} (${d.filter((x) => x.family).length} dishes) | — |
| Dishes with multiple origins | ${d.filter((x) => x.origins.length > 1).length} | — |
| Possible duplicates | ${dupes.length} | 0 |

**Provinces without dishes:** ${provinces.filter((p) => !covered.has(p.id)).map((p) => p.nameVi).join(", ") || "none"}.

**Possible duplicates (review):** ${dupes.length ? dupes.join("; ") : "none detected"}.

### By region
| Region | Dishes | With photo | With HCMC venue |
| --- | ---: | ---: | ---: |
${regions.map((r) => { const rd = d.filter((x) => x.regionIds.includes(r.id as never)); return `| ${r.nameVi} | ${rd.length} | ${rd.filter((x) => x.photos.length).length} | ${rd.filter((x) => venueCount.has(x.id)).length} |`; }).join("\n")}

## Photography (\`data/source/dish-photos.json\`)
- Licensed Wikimedia Commons photos attached: ${d.filter((x) => x.photos.length).length}. Licences: ${[...new Set(d.flatMap((x) => x.photos.map((p) => p.license)))].join(", ")}.
- Candidates rejected as not showing the named dish: ${Object.keys(photosMeta.rejected ?? {}).length} (${Object.entries(photosMeta.rejected ?? {}).map(([k, v]) => `${k}: ${v}`).join("; ")}).
- Photos are hot-linked from Commons; rendering is not verifiable from the build sandbox (Wikimedia bot policy) — needs a check in a normal browser.

## HCMC establishments
| Metric | Actual | Sprint-2 target |
| --- | --- | --- |
| Real establishments | ${restaurants.length} | 100+ verified |
| …with exact (building) coordinates | ${exactPins} | — |
| …with street-level coordinates (flagged approximate) | ${restaurants.length - exactPins} | — |
| Dish ↔ establishment links | ${links.length} | 200+ verified |
${(["visit-confirmed", "directly-confirmed", "menu-confirmed", "source-listed", "temporarily-unavailable", "candidate"] as const).map((s) => `| …${s} | ${links.filter((l) => l.status === s).length} | — |`).join("\n")}
| Dishes with ≥ 1 venue | ${pct(venueCount.size)} | — |
| Dishes with ≥ 5 venues | ${pct([...venueCount.values()].filter((n) => n >= 5).length)} | PO wish: all |
| Links with a price | ${links.filter((l) => l.priceVnd).length} | when reliably available |

Evidence levels: see \`src/lib/data/evidence.ts\` and \`docs/RESTAURANT_VERIFICATION_PLAN.md\`. See \`docs/RESTAURANT_VERIFICATION_PLAN.md\`.

## Priority 50 regional dishes (\`data/source/priority-dishes.json\`)
${(() => {
  const ids: string[] = read("data/source/priority-dishes.json").dishIds;
  const rows = ids.map((id) => { const x = d.find((y) => y.id === id)!; const n = venueCount.get(id) ?? 0; return { x, n }; });
  const done = rows.filter((r) => r.n >= 5).length, some = rows.filter((r) => r.n > 0 && r.n < 5).length;
  return `≥ 5 listed venues: **${done}** · 1–4: **${some}** · none: **${rows.length - done - some}** · first-hand confirmed: **0**\n\n| # | Dish | Region | Listed venues | Photo |\n| ---: | --- | --- | ---: | --- |\n` +
    rows.map((r, i) => `| ${i + 1} | ${r.x.nameVi} | ${regions.find((g) => g.id === r.x.regionIds[0])?.nameVi} | ${r.n} | ${r.x.photos.length ? "✓" : "—"} |`).join("\n");
})()}

## Validation
All files above passed schema validation (Zod) while generating this report. Integrity rules (HCMC boundary, province/region consistency, evidence requirements) are enforced by \`npm run data:validate\`.
`;
writeFileSync(path.join(root, "docs/DATA_REPORT.md"), md);
console.log(`✓ docs/DATA_REPORT.md — ${d.length} dishes, ${restaurants.length} venues, ${dupes.length} possible duplicates`);
