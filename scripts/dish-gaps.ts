/**
 * Dish gaps checklist → research-exchange/briefs/DISH-GAPS.md
 *   npm run data:gaps   (run after `npm run data:food-coverage`, which it reads)
 * Lists the dishes that still need an HCMC venue and/or a photo, so whoever collects Google Maps share links or
 * takes photos knows what to do next. Venue counts come from docs/food-coverage.json (same real-only index as
 * the app); "photo" means at least one licensed photo on the dish (data/vietnamese-dishes.json → photos).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), "utf8"));
type Dish = { id: string; nameVi: string; regionIds: string[]; dataset?: string; photos?: unknown[] };
const dishes: Dish[] = read("data/vietnamese-dishes.json").dishes;
const coverage: { dishes: { id: string; venues: number }[] } = read("docs/food-coverage.json");
const regionsRaw = read("data/regions.json");
const regions: { id: string; nameVi: string; nameEn: string }[] = Array.isArray(regionsRaw) ? regionsRaw : regionsRaw.regions;
const venues = new Map(coverage.dishes.map((d) => [d.id, d.venues]));
if (venues.size !== dishes.length) throw new Error(`docs/food-coverage.json covers ${venues.size} dishes, catalogue has ${dishes.length} — run npm run data:food-coverage first`);

const count = (d: Dish) => venues.get(d.id) ?? 0;
const hasPhoto = (d: Dish) => (d.photos?.length ?? 0) > 0;
const both = dishes.filter((d) => count(d) === 0 && !hasPhoto(d));
const venueNoPhoto = dishes.filter((d) => count(d) > 0 && !hasPhoto(d)).sort((a, b) => count(b) - count(a));
const photoNoVenue = dishes.filter((d) => count(d) === 0 && hasPhoto(d));
const complete = dishes.filter((d) => count(d) > 0 && hasPhoto(d));

const groupOf = (d: Dish) => {
  if (d.dataset && d.dataset !== "seed") return "New everyday dishes (master catalogue)";
  const r = regions.find((x) => x.id === d.regionIds[0]);
  return r ? `${r.nameVi} · ${r.nameEn}` : "Other";
};
const groups = new Map<string, Dish[]>();
for (const d of both) groups.set(groupOf(d), [...(groups.get(groupOf(d)) ?? []), d]);
const order = ["New everyday dishes (master catalogue)", ...regions.map((r) => `${r.nameVi} · ${r.nameEn}`), "Other"];

const box = (d: Dish, extra = "") => `- [ ] ${d.nameVi} \`${d.id}\`${extra}`;
const L: string[] = [
  "# Dish gaps — venues and photos still needed",
  "",
  `Generated by \`npm run data:gaps\` from \`docs/food-coverage.json\` and \`data/vietnamese-dishes.json\`. Do not edit by hand; regenerate after each import.`,
  "",
  `**${dishes.length} dishes:** ${complete.length} complete (venue + photo) · **${both.length} need both** · ${venueNoPhoto.length} need a photo · ${photoNoVenue.length} need a venue.`,
  "",
  "**How to fill a gap**",
  "- **Venue:** open the dish page → *Search on Google Maps* → for each good venue (open, well reviewed, the dish is in its name or Menu tab) send Claude Code the *Share* link plus the address line. Name and exact pin are read from the link. See `GMAPS-DISH-VENUES.md`.",
  "- **Photo:** only licensed photos — your own photo of the dish (taken at a venue), a venue's photo with its permission, or a free Wikimedia Commons photo of this exact dish. Never copy Google Maps or blog photos.",
  "",
  `## 1. Need a venue and a photo (${both.length})`,
  "",
];
for (const g of order) {
  const list = groups.get(g);
  if (!list?.length) continue;
  L.push(`### ${g} (${list.length})`, "", ...list.map((d) => box(d)), "");
}
L.push(`## 2. Have venues, need a photo (${venueNoPhoto.length})`, "", "Best candidates for your own photos — you can eat these in HCMC today.", "",
  ...venueNoPhoto.map((d) => box(d, ` — ${count(d)} venue${count(d) === 1 ? "" : "s"}`)), "",
  `## 3. Have a photo, need a venue (${photoNoVenue.length})`, "", ...photoNoVenue.map((d) => box(d)), "");
writeFileSync(path.join(root, "research-exchange/briefs/DISH-GAPS.md"), L.join("\n"));
console.log(`✓ research-exchange/briefs/DISH-GAPS.md — ${dishes.length} dishes: ${both.length} need both, ${venueNoPhoto.length} need a photo, ${photoNoVenue.length} need a venue, ${complete.length} complete`);
