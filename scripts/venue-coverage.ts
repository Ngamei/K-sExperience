/**
 * Writes docs/VENUE_COVERAGE.md: real HCMC venues per dish, target ≥ 5.
 *   npm run data:coverage
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
const root = path.resolve(__dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), "utf8"));
const dishes = read("data/vietnamese-dishes.json").dishes as { id: string; nameVi: string; regionIds: string[] }[];
const links = read("data/dish-restaurant-mapping.json").links as { dishId: string }[];
const count = new Map<string, number>();
links.forEach((l) => count.set(l.dishId, (count.get(l.dishId) ?? 0) + 1));
const rows = dishes.map((d) => ({ ...d, n: count.get(d.id) ?? 0 })).sort((a, b) => b.n - a.n || a.nameVi.localeCompare(b.nameVi, "vi"));
const done = rows.filter((r) => r.n >= 5).length;
const some = rows.filter((r) => r.n > 0 && r.n < 5).length;
const md = `# HCMC venue coverage

_Generated by \`npm run data:coverage\` on ${new Date().toISOString().slice(0, 10)}. Target (PO): at least 5 real, sourced HCMC venues per dish._

| | Dishes |
| --- | --- |
| ≥ 5 venues | ${done} |
| 1–4 venues | ${some} |
| 0 venues | ${rows.length - done - some} |
| **Total** | ${rows.length} |

Real venues: ${read("data/hcmc-restaurants.json").restaurants.length}. Research batches live in \`data/source/venue-research/\`; venues whose street name was ambiguous (no district in the source) are skipped rather than guessed.

| Dish | Venues | Status |
| --- | ---: | --- |
${rows.map((r) => `| ${r.nameVi} (\`${r.id}\`) | ${r.n} | ${r.n >= 5 ? "✅" : r.n > 0 ? "🟡" : "⬜"} |`).join("\n")}
`;
writeFileSync(path.join(root, "docs/VENUE_COVERAGE.md"), md);
console.log(`≥5: ${done} · 1–4: ${some} · 0: ${rows.length - done - some}`);
