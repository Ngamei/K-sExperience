/**
 * Venues whose Google Maps search link is most likely to open the wrong place or a list, so a researcher should
 * paste the exact Google Maps "Share" link (google.com/maps/place/… or maps.app.goo.gl/…) into a batch.
 *   npm run data:maps-share-list  →  research-exchange/briefs/MAPS-SHARE-LINKS.md + .csv
 * Reasons (a venue can have several): no district in the address · one of several branches of the same brand ·
 * alley address (hẻm, "a/b" house number) · approximate (street-level) pin. Venues that already have an exact
 * place link are skipped. Nothing here is fetched from Google.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { googleMapsQuery, isGoogleMapsPlaceUrl } from "../src/lib/geo/maps-link";

const root = path.resolve(__dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), "utf8"));
type E = { id: string; name: string; address: string; isSample?: boolean; coordinatePrecision?: string; googleMapsUrl?: string; attributes?: { brand?: string } };
const rows: (E & { mode: string })[] = [
  ...(read("data/hcmc-restaurants.json").restaurants as E[]).map((e) => ({ ...e, mode: "food" })),
  ...["coffee", "bars", "spa", "sport"].flatMap((m) => (read(`data/experiences/${m}.json`).establishments as E[]).map((e) => ({ ...e, mode: m }))),
].filter((e) => !e.isSample && !isGoogleMapsPlaceUrl(e.googleMapsUrl));

const DISTRICT = /(quận \d|phú nhuận|bình thạnh|thủ đức|thảo điền|gò vấp|tân bình|tân phú|bình tân|nhà bè|bình chánh|thủ thiêm|an phú|củ chi|hóc môn|cần giờ)/i;
const brandOf = (e: E) => (e.attributes?.brand ?? e.name.replace(/\s*\([^)]*\)\s*/g, " ").replace(/\s+[–-]\s+.*$/, "").trim()).toLowerCase();
const brandCount = new Map<string, number>();
for (const e of rows) brandCount.set(brandOf(e), (brandCount.get(brandOf(e)) ?? 0) + 1);

const WEIGHT = { "no district": 3, "several branches": 3, "alley address": 2, "approximate pin": 1 } as const;
const out = rows.map((e) => {
  // the search text actually stored (module importers add the batch district); rebuilt only if missing
  const q = (e.googleMapsUrl && new URL(e.googleMapsUrl).searchParams.get("query")) || googleMapsQuery(e.name, e.address);
  const reasons: (keyof typeof WEIGHT)[] = [];
  if (!DISTRICT.test(q)) reasons.push("no district");
  if ((brandCount.get(brandOf(e)) ?? 0) > 1) reasons.push("several branches");
  if (/\d+[A-Z]?\/\d+/.test(e.address.split(",")[0]) || /(^|,\s*)(hẻm|ngõ|kiệt)\s/i.test(e.address)) reasons.push("alley address");
  if (e.coordinatePrecision === "street") reasons.push("approximate pin");
  return { ...e, q, reasons, score: reasons.reduce((s, r) => s + WEIGHT[r], 0) };
}).filter((e) => e.reasons.some((r) => r !== "approximate pin"))
  .sort((a, b) => b.score - a.score || a.mode.localeCompare(b.mode) || a.name.localeCompare(b.name, "vi"));

const priority = (s: number) => (s >= 4 ? "P1" : s >= 3 ? "P2" : "P3");
const csv = ["priority,mode,id,name,address,reasons,current_search_text,share_link",
  ...out.map((e) => [priority(e.score), e.mode, e.id, e.name, e.address, e.reasons.join("; "), e.q, ""].map((v) => `"${String(v).replace(/"/g, '""')}"`).join(","))].join("\n");
writeFileSync(path.join(root, "research-exchange/briefs/MAPS-SHARE-LINKS.csv"), csv + "\n");
const count = (p: string) => out.filter((e) => priority(e.score) === p).length;
const md = [
  "# Venues that need an exact Google Maps Share link", "",
  "Generated by `npm run data:maps-share-list`. These venues' search links are the most likely to open a list, another branch or nothing. For each one: open Google Maps, find **this** venue (same name, house number and street), tap **Share → Copy link**, and put it in the `share_link` column of `MAPS-SHARE-LINKS.csv` (or as `googleMapsUrl` in a research batch). Only `google.com/maps/place/…` or `maps.app.goo.gl/…` links are accepted. If you cannot find the venue at that address, write `NOT FOUND` — that is a useful finding (it may have moved or closed). Do not copy ratings, hours or photos from Google.", "",
  `**${out.length} venues** of ${rows.length} without an exact link · P1 ${count("P1")} · P2 ${count("P2")} · P3 ${count("P3")}. Reasons: no district in the address · one of several branches of the same brand · alley address (hẻm / "a/b" numbers) · approximate pin (only counted together with another reason).`, "",
  "| # | Priority | Mode | Venue | Address | Why |", "| --- | --- | --- | --- | --- | --- |",
  ...out.map((e, i) => `| ${i + 1} | ${priority(e.score)} | ${e.mode} | ${e.name} | ${e.address} | ${e.reasons.join(", ")} |`), "",
].join("\n");
writeFileSync(path.join(root, "research-exchange/briefs/MAPS-SHARE-LINKS.md"), md);
console.log(`✓ ${out.length} venues need a Share link (P1 ${count("P1")}, P2 ${count("P2")}, P3 ${count("P3")}) → research-exchange/briefs/MAPS-SHARE-LINKS.md`);
